import type { PyramidBlock } from './domains';

/** メニューの対象区分。メニュー構築サイトの対象年齢（未就学児向け・小学校低学年向け・小学校高学年向け）に当たる。 */
export type MenuAudience = 'pre' | 'low' | 'high';

/** メニューの難易度（初級・中級・上級）。メニュー構築サイトの「筋トレ系」は選ぶときだけ中級として扱う。 */
export const MENU_LEVELS = ['初級', '中級', '上級'] as const;
export type MenuLevel = (typeof MENU_LEVELS)[number];

/**
 * コーチ向けの「方針とメニューの方向性」に出すメニュー1件。メニュー構築サイトの Activity から写したもの（menu-catalog.ts）。
 * コーチはメニュー構築サイトで名前から検索するので、名前は DB の文字列を前後の空白だけ落として持つ。
 */
export interface CatalogMenu {
  /** メニュー構築サイトの Activity の id。表示しない。出力を取り直したときに、名前の変更やアーカイブを見つけるのに使う。 */
  id: string;
  name: string;
  /** 「同じ系列は2件まで」の判定に使う。名前の「_」より前が初期値。 */
  series: string;
  /** 難易度（メニュー構築サイトの値そのまま。初級・中級・上級・筋トレ系）。 */
  difficulty: string;
  audiences: readonly MenuAudience[];
  /** 実施形態（一人でもできるか）。 */
  form: '一人でも' | '親子で';
  equipment: string;
  /** 親の負担。多いときだけ「多」。 */
  parentBurden?: '多';
  /** カテゴリ／サブカテゴリ。 */
  category: string;
}

